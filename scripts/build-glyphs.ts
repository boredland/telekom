// Maintains the captcha glyph templates in src/glyphs.ts from labelled captchas in captcha/train/<n>-<TEXT>.png.
//
//   node scripts/build-glyphs.ts build              # regenerate src/glyphs.ts from captcha/train
//   node scripts/build-glyphs.ts eval               # solve captcha/test with the current templates, report accuracy
//   node scripts/build-glyphs.ts label <dir>        # pre-label unlabelled PNGs in <dir> by renaming to <n>-<guess>.png
//
// Labels are case-sensitive, so the filesystem must be too. Pre-labels are guesses: check them before moving to train/.

import { readdirSync, readFileSync, renameSync, writeFileSync } from "node:fs";
import { basename, join } from "node:path";
import { classify, decodePng, decodeTemplates, encodeTemplates, segment, similarity, solveCaptcha, type Template } from "../src/captcha.ts";
import { GLYPHS } from "../src/glyphs.ts";

const ROOT = new URL("..", import.meta.url).pathname;
// Identical renderings recur across captchas; one copy is enough.
const DUPLICATE_SIMILARITY = 0.995;

function labelled(dir: string): { file: string; text: string }[] {
	return readdirSync(dir)
		.filter((f) => f.endsWith(".png"))
		.sort()
		.map((f) => ({ file: join(dir, f), text: basename(f, ".png").split("-")[1] ?? "" }));
}

async function build() {
	const templates: Template[] = [];
	for (const { file, text } of labelled(join(ROOT, "captcha/train"))) {
		const glyphs = segment(await decodePng(readFileSync(file)));
		if (glyphs.length !== text.length) throw new Error(`${file}: ${glyphs.length} glyphs for label "${text}"`);
		glyphs.forEach((g, i) => {
			const char = text[i];
			if (!templates.some((t) => t.char === char && t.w === g.w && t.h === g.h && similarity(g, t) >= DUPLICATE_SIMILARITY)) {
				templates.push({ ...g, char });
			}
		});
	}
	const encoded = encodeTemplates(templates);
	writeFileSync(
		join(ROOT, "src/glyphs.ts"),
		`// Generated by scripts/build-glyphs.ts from captcha/train; do not edit.\n// ${templates.length} glyphs, characters: ${[...new Set(templates.map((t) => t.char))].sort().join("")}\nexport const GLYPHS = "${encoded}";\n`,
	);
	console.log(`${templates.length} glyphs, ${encoded.length} bytes base64`);
}

async function evaluate() {
	const templates = decodeTemplates(GLYPHS);
	let solved = 0;
	let wrong = 0;
	let skipped = 0;
	const cases = labelled(join(ROOT, "captcha/test"));
	for (const { file, text } of cases) {
		const answer = await solveCaptcha(readFileSync(file), templates);
		if (answer === text) solved++;
		else if (answer === undefined) {
			skipped++;
			const glyphs = segment(await decodePng(readFileSync(file)));
			const detail = glyphs.map((g) => classify(g, templates)).map((m) => `${m?.char}:${m?.score.toFixed(3)}/${m?.margin.toFixed(3)}`);
			console.log(`skip  ${basename(file)}  ${detail.join(" ")}`);
		} else {
			wrong++;
			console.log(`WRONG ${basename(file)}  read ${answer}`);
		}
	}
	console.log(`${cases.length} captchas: ${solved} solved, ${skipped} skipped (refetch), ${wrong} wrong`);
}

async function label(dir: string) {
	const templates = decodeTemplates(GLYPHS);
	for (const f of readdirSync(dir).filter((f) => /^\d+\.png$/.test(f))) {
		const glyphs = segment(await decodePng(readFileSync(join(dir, f))));
		const guess = glyphs.map((g) => classify(g, templates)?.char ?? "_").join("");
		renameSync(join(dir, f), join(dir, `${basename(f, ".png")}-${guess}.png`));
	}
}

const [command, arg] = process.argv.slice(2);
if (command === "build") await build();
else if (command === "eval") await evaluate();
else if (command === "label" && arg) await label(arg);
else {
	console.error("usage: build-glyphs.ts build | eval | label <dir>");
	process.exit(1);
}
